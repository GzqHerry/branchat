import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const base=fileURLToPath(new URL('../',import.meta.url));
const dependencyRoot=process.env.TREE_MATH_DEPS?path.resolve(process.env.TREE_MATH_DEPS):base;
const require=createRequire(path.join(dependencyRoot,'package.json'));
const {build}=require('esbuild');
await build({entryPoints:[path.join(base,'src/markdown.js')],outfile:path.join(base,'public/markdown.js'),bundle:true,format:'esm',platform:'browser',target:'es2022',external:['./marked.js'],nodePaths:[path.join(dependencyRoot,'node_modules')],minify:true,legalComments:'inline',banner:{js:'// Generated by scripts/build-markdown.mjs. Edit src/markdown.js instead.'}});
